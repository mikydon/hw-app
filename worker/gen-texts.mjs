// Writes worker/texts.js: the notification lines from the app's own translations (src/i18n), so the push server
// speaks the same languages as the app. Run after changing them: node worker/gen-texts.mjs
import fs from "fs";
const dir = new URL("../src/i18n/", import.meta.url);
const KEYS = ["ntReq", "ntReqD", "ntAcc", "ntAccD", "ntTest", "ntTestD"];
const out = {};
for (const f of fs.readdirSync(dir).filter(f => /^[a-z]{2}\.js$/.test(f))) {
  const m = await import(new URL(f, dir));
  const ui = (m.default || m).ui || {};
  out[f.slice(0, 2)] = Object.fromEntries(KEYS.map(k => [k, ui[k] || ""]));
}
fs.writeFileSync(new URL("./texts.js", import.meta.url), "// Generated by gen-texts.mjs from src/i18n (do not edit by hand).\nexport default " + JSON.stringify(out, null, 1) + ";\n");
console.log("texts for", Object.keys(out).join(" "));
